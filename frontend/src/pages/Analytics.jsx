
import { useEffect, useMemo, useState } from 'react'
import './Analytics.css'
import { getPredictions } from '../services/api.js'

const MODEL_METRICS = {
  mae: 0.297858779888588,
  rmse: 0.5257446282642554,
  r2: 0.8672954006454285,
}

function Analytics() {
  const [records, setRecords] = useState([])
  const [selectedMetric, setSelectedMetric] = useState('co')
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  useEffect(() => {
    async function loadAnalytics() {
      try {
        const response = await getPredictions()
        setRecords(response.data || [])
      } catch (err) {
        setError(err.message || 'Unable to load prediction records.')
      } finally {
        setLoading(false)
      }
    }

    loadAnalytics()
  }, [])

  const metricDetails = {
    co: {
      title: 'Predicted Carbon Monoxide (CO)',
      unit: 'mg/m³',
      description: 'CO(GT) estimates generated by your XGBoost model.',
      color: '#13865f',
      getValue: record => record.predictedCO,
    },
  }

  const metric = metricDetails[selectedMetric]

  const chartData = useMemo(() => {
    return [...records]
      .filter(record => Number.isFinite(Number(record.predictedCO)))
      .sort(
        (a, b) =>
          new Date(a.createdAt).getTime() -
          new Date(b.createdAt).getTime()
      )
      .slice(-8)
  }, [records])

  const averageCO = records.length
    ? records.reduce(
        (sum, record) => sum + (Number(record.predictedCO) || 0),
        0
      ) / records.length
    : 0

  const maximum = Math.max(
    1,
    ...chartData.map(record => Number(record.predictedCO))
  )

  return (
    <main className="analytics-page">
      <div className="analytics-heading">
        <span className="analytics-label">DATA EXPLORATION</span>
        <h1>Air Quality Analytics</h1>
        <p>
          Explore saved CO predictions and evaluate your trained
          XGBoost regression model.
        </p>
      </div>

      <section className="analytics-panel">
        <div className="analytics-panel-heading">
          <div>
            <h2>{metric.title}</h2>
            <p>{metric.description}</p>
          </div>

          <select
            value={selectedMetric}
            onChange={event => setSelectedMetric(event.target.value)}
            aria-label="Select pollution metric"
          >
            <option value="co">Predicted Carbon Monoxide</option>
          </select>
        </div>

        {loading ? (
          <p>Loading analytics from MongoDB...</p>
        ) : error ? (
          <div className="analytics-note">
            <i className="bi bi-exclamation-circle"></i>
            <p>{error}</p>
          </div>
        ) : chartData.length === 0 ? (
          <p>No prediction records are available yet.</p>
        ) : (
          <div className="analytics-chart">
            {chartData.map(record => {
              const value = metric.getValue(record)
              const height = Math.max(
                5,
                (Number(value) / maximum) * 100
              )

              return (
                <div className="chart-column" key={record._id}>
                  <span className="chart-value">
                    {Number(value).toFixed(3)}
                  </span>

                  <div className="chart-bar-area">
                    <div
                      className="chart-bar"
                      style={{
                        height: `${height}%`,
                        backgroundColor: metric.color,
                      }}
                    />
                  </div>

                  <span className="chart-month">
                    {new Date(record.createdAt).toLocaleDateString(
                      'en-IN',
                      { day: '2-digit', month: 'short' }
                    )}
                  </span>
                </div>
              )
            })}
          </div>
        )}

        <div className="chart-unit">
          Measurement unit: {metric.unit}
        </div>
      </section>

      <section className="analytics-panel">
        <h2>Prediction Summary</h2>

        <div className="row g-3 mt-2">
          <div className="col-md-4">
            <div className="p-3 rounded-3 bg-light">
              <h3>{records.length}</h3>
              <p className="mb-0">Saved predictions</p>
            </div>
          </div>

          <div className="col-md-4">
            <div className="p-3 rounded-3 bg-light">
              <h3>
                {records.length ? averageCO.toFixed(3) : '--'}
              </h3>
              <p className="mb-0">Average predicted CO (mg/m³)</p>
            </div>
          </div>

          <div className="col-md-4">
            <div className="p-3 rounded-3 bg-light">
              <h3>
                {records.length
                  ? Math.max(
                      ...records.map(record =>
                        Number(record.predictedCO) || 0
                      )
                    ).toFixed(3)
                  : '--'}
              </h3>
              <p className="mb-0">Highest predicted CO (mg/m³)</p>
            </div>
          </div>
        </div>
      </section>

      <section className="analytics-panel">
        <h2>XGBoost Model Performance</h2>
        <p>Evaluation metrics from your saved test-set report.</p>

        <div className="row g-3 mt-2">
          <div className="col-md-4">
            <div className="p-3 rounded-3 bg-light">
              <h3>{MODEL_METRICS.mae.toFixed(4)}</h3>
              <p className="mb-0">MAE</p>
            </div>
          </div>

          <div className="col-md-4">
            <div className="p-3 rounded-3 bg-light">
              <h3>{MODEL_METRICS.rmse.toFixed(4)}</h3>
              <p className="mb-0">RMSE</p>
            </div>
          </div>

          <div className="col-md-4">
            <div className="p-3 rounded-3 bg-light">
              <h3>{MODEL_METRICS.r2.toFixed(4)}</h3>
              <p className="mb-0">R² Score</p>
            </div>
          </div>
        </div>
      </section>

      <section className="analytics-note">
        <i className="bi bi-info-circle"></i>
        <p>
          Prediction charts and summaries use records saved in MongoDB.
          Model metrics come from the XGBoost test-set evaluation.
          These are model estimates, not live sensor readings.
        </p>
      </section>
    </main>
  )
}

export default Analytics
